/// Whether `name` (a widget `runtimeType`, generics allowed) is a framework widget.
pub fn is_framework_widget(name: &str) -> bool {
    let base = name.split('<').next().unwrap_or(name);
    FRAMEWORK_WIDGETS.binary_search(&base).is_ok()
}

